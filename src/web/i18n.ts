const dictionaries: Record<Locale, Record<MessageKey, string>> = { zh, en };

export function resolveLocale(
  configured: 'system' | 'zh-CN' | 'zh' | 'en' | undefined,
  navigatorLanguage: string
): Locale {
  if (configured === 'zh-CN' || configured === 'zh') return 'zh';
  if (configured === 'en') return 'en';
  return navigatorLanguage.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export function translate(
  locale: Locale,
  key: MessageKey,
  params?: Record<string, string | number>
): string {
  let value: string = dictionaries[locale][key] ?? dictionaries.zh[key] ?? key;
  if (params) {
    for (const [name, replacement] of Object.entries(params)) {
      value = value.split(`{${name}}`).join(String(replacement));
    }
  }
  return value;
}

export type Translate = (
  key: MessageKey,
  params?: Record<string, string | number>
) => string;
export type { MessageKey };
